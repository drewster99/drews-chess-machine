#!/usr/bin/env python3
"""Verify the optimizer-velocity layout of every weight tensor against the data.

Two independent tests, on each run that saves velocity (leaky-FC1, ReLU seed 2):

1. Stem conv (OIHW hypothesis vs the alternatives IOHW / HWIO / OHWI): the
   stem weights reading the always-zero input planes (19, 20, 21, 22, 24, 26,
   28) never get a gradient, so under the right layout every velocity element
   of those planes is exactly 0 while the other planes are mostly nonzero.
2. Every weight tensor: Spearman rank correlation between |velocity| and
   |gradient-driven weight change| over the last 1,000 steps, where the change
   is `w_N - f * w_(N-1000)` with `f` the decay-only shrink factor over that
   interval (measured on the always-zero-plane stem weights). Momentum velocity
   is a short exponential average of recent gradients, so units/elements with
   persistently large gradients have both large |v| and large |dw|: the right
   layout correlates clearly; the wrong one (a transpose) is near 0.

Writes results/layout_check.md.
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fma_lib as L  # noqa: E402


def decay_factor(now, before):
    w1 = now["stem.conv.weight"][:, L.ALWAYS_ZERO_PLANES]
    w0 = before["stem.conv.weight"][:, L.ALWAYS_ZERO_PLANES]
    return float(np.linalg.norm(w1) / np.linalg.norm(w0))


def main():
    lines = ["# Velocity layout check", "",
             "Generated by `scripts/layout_check.py`. See the script docstring for the method.", ""]
    for run in ("leaky", "relu_s2"):
        files, _, _ = L.discover(run)
        steps = sorted(s for s in files if s > 0)
        latest = steps[-1] if steps[-1] % 1000 == 0 else steps[-2]
        now = L.Checkpoint(files[latest])
        before = L.Checkpoint(files[latest - 1000])
        f = decay_factor(now, before)
        lines += [f"## {run}: {now.file} (ModelID {now.model_id}, step {now.training_step}) vs step {before.training_step}", "",
                  f"Decay-only shrink factor over the interval (always-zero stem planes): {f:.8f}", ""]
        # Test 1: stem layouts.
        flat = now["opt.stem.conv.weight.velocity"].reshape(-1)
        candidates = {
            "OIHW [128,30,7,7]": flat.reshape(128, 30, 7, 7),
            "IOHW [30,128,7,7]": flat.reshape(30, 128, 7, 7).transpose(1, 0, 2, 3),
            "HWIO [7,7,30,128]": flat.reshape(7, 7, 30, 128).transpose(3, 2, 0, 1),
            "OHWI [128,7,7,30]": flat.reshape(128, 7, 7, 30).transpose(0, 3, 1, 2),
        }
        other = [p for p in range(30) if p not in L.ALWAYS_ZERO_PLANES]
        lines += ["Test 1 -- stem velocity, share of exactly-zero elements:", "",
                  "| layout hypothesis | always-zero planes | other planes |", "|---|---:|---:|"]
        for label, v in candidates.items():
            z_dead = float(np.mean(v[:, L.ALWAYS_ZERO_PLANES] == 0))
            z_live = float(np.mean(v[:, other] == 0))
            lines.append(f"| {label} | {z_dead:.4f} | {z_live:.4f} |")
        lines.append("")
        # Test 2: rank correlation per tensor.
        lines += ["Test 2 -- Spearman(|v|, |w_N - f w_(N-1000)|) per weight tensor:", "",
                  "| tensor | saved shape | native-layout hypothesis | rho | alternative (transpose) | rho |",
                  "|---|---|---|---:|---|---:|"]
        for name in sorted(n for n in now.tensors if not n.startswith("opt.") and n.endswith(".weight")
                           and f"opt.{n}.velocity" in now.tensors):
            shape = now[name].shape
            if len(shape) == 1:
                continue
            dw = np.abs(now[name] - f * before[name])
            flat = now[f"opt.{name}.velocity"]
            if L.is_linear_weight(name, shape):
                v_a = L.velocity_as_weight(flat, shape, name, "in_out")
                v_b = L.velocity_as_weight(flat, shape, name, "out_in")
                label_a, label_b = "[in,out] (graph)", "[out,in] (as saved)"
            else:
                v_a = flat.reshape(shape)
                o, i = shape[0], shape[1]
                v_b = flat.reshape((i, o) + tuple(shape[2:])).swapaxes(0, 1)
                label_a, label_b = "OIHW (as saved)", "IOHW"
            rho_a = L.spearman(np.abs(v_a), dw)
            rho_b = L.spearman(np.abs(v_b), dw)
            lines.append(f"| `{name}` | {list(shape)} | {label_a} | {rho_a:+.3f} | {label_b} | {rho_b:+.3f} |")
        lines.append("")
    out = os.path.join(L.RESULTS_DIR, "layout_check.md")
    with open(out, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
